/* ---------------------------------------------------------------------------
   assumptions.js  —  EDITABLE PLACEHOLDERS
   ---------------------------------------------------------------------------
   Every number the management pitch quotes comes from this file and nowhere
   else. They are ILLUSTRATIVE PLACEHOLDERS, not Chillibyte figures. Replace
   them with real numbers before presenting. The deck labels them as
   assumptions on screen so nothing is passed off as fact.
--------------------------------------------------------------------------- */

export const assumptions = {
  currency: "£",

  // --- Commercial basis -----------------------------------------------------
  // CONFIRMED CHILLIBYTE FIGURES (not placeholders).
  hourlyRate: 75, // £ blended charge-out rate
  hoursPerDay: 7.5, // only used to express savings in days
  projectsPerYear: 25, // website projects delivered per year
  avgProjectValue: 8000, // £ total per project, INCLUDING account management

  // Sanity anchor, derived: £8,000 ÷ £75 = ~107 hours of billable work per
  // average project, account management included. Every "hours lost" and
  // "hours of overhead" figure below has to look sensible against 107 — not
  // against the 200-hour standard-route baseline in the spec builder, which
  // describes a larger-than-average project.

  // --- The leaks (per project, today) --------------------------------------
  // Hours currently lost per project. STILL ESTIMATES — these are the numbers
  // to measure first, and the trial exists to replace them with actuals.
  //
  // Scaled to a ~107-hour project. Together they are 16 hours, about 15% —
  // roughly a day and a half per project. It is tempting to make them bigger;
  // resist it. A figure that sounds implausible gets the whole pitch
  // dismissed, and you cannot defend a number you have not measured.
  leaks: {
    rework: {
      hours: 6,
      label: "Rework",
      detail:
        "Design redone because structure changed underneath it; blocks rebuilt because scope was discovered late.",
    },
    unbilledChanges: {
      hours: 5,
      label: "Unbilled changes",
      detail:
        "Client additions absorbed rather than charged, because nothing proves they were not in scope.",
    },
    waiting: {
      hours: 3,
      label: "Idle waiting",
      detail:
        "Work stalled on content, approvals or credentials that nobody had chased to a deadline.",
    },
    launchScramble: {
      hours: 2,
      label: "Launch scramble",
      detail:
        "Compressed QA, last-minute content entry and out-of-hours launch fixes.",
    },
  },

  // --- Expected recovery ----------------------------------------------------
  // Share of each leak the process is expected to recover. Deliberately
  // conservative: the process does not claim to eliminate any leak entirely.
  recovery: {
    rework: 0.55,
    unbilledChanges: 0.7, // mostly *converted to billable*, not eliminated
    waiting: 0.4,
    launchScramble: 0.5,
  },

  // --- Cost of running the process -----------------------------------------
  // Honest counterweight: the process is not free. This is subtracted from the
  // recovery before any return is claimed.
  //
  // processOverheadHours is the SUM of overheadBreakdown below — the deck
  // shows the itemisation on slide 7 so the number can be challenged line by
  // line rather than taken on trust. Keep them consistent; the deck warns if
  // they drift apart.
  // Scaled to a ~107-hour project, which is mostly light-to-standard route.
  // The earlier 8-hour figure was calibrated for a 200-hour build and would
  // have consumed most of the recovery at this project size.
  processOverheadHours: 4.5, // extra hours per project spent on artefacts/gates
  overheadBreakdown: [
    ["Gate tickets", 1.0, "11–15 gates at about 5 minutes each to raise and close"],
    ["Estimate baseline", 0.5, "Generated by the spec builder, then sense-checked"],
    ["Decision, change and variation logs", 1.0, "A few minutes per entry, not per day"],
    ["Sales handover note", 0.5, "Written once, by sales, straight from the proposal"],
    ["Extra artefact depth", 1.5, "Writing down what is currently only said out loud"],
  ],

  setupHoursOneOff: 16, // one-off: templates, training, first-project bedding-in

  // --- Capacity / growth ----------------------------------------------------
  // Kept deliberately modest. The argument here does not need big numbers — it
  // needs believable ones. "Half a day down to an hour" is easy to picture and
  // hard to argue with; "two days down to twenty minutes" invites a fight.
  capacity: {
    peoplePerProjectNow: 1.2, // effective concurrent contributors today
    peoplePerProjectTarget: 1.8, // with work packages that have entry/exit criteria
    onboardHoursNow: 4, // hours to get a developer productive on a live project
    onboardHoursTarget: 1, // with a build spec and defined work packages
  },

  // --- Bigger-project argument ---------------------------------------------
  // "Comfortable ceiling" = the project size we can take on today WITHOUT it
  // becoming a risk to the business — i.e. one we could staff, govern and
  // survive if it went wrong. Not the largest we have ever invoiced.
  biggerProjects: {
    currentCeiling: 20000, // £ largest project we can comfortably absorb today
    targetCeiling: 40000, // £ what the process makes comfortable
    extraWinsPerYear: 1, // additional larger projects/year assumed
  },

  // --- Adoption ask ---------------------------------------------------------
  ask: {
    trialProjects: 3,
    reviewAfterWeeks: 12,
  },
};

/* --- Derived figures. Pure functions so the deck calculator can re-run them
   against user-adjusted inputs without touching the defaults above. ------ */

export function model(a = assumptions) {
  // Hourly is the primary input — it is how the rate is actually quoted.
  // dayRate is kept as a fallback so an older saved config still works.
  const hourRate = a.hourlyRate ?? a.dayRate / a.hoursPerDay;

  const leakRows = Object.entries(a.leaks).map(([key, leak]) => {
    const recovered = leak.hours * (a.recovery[key] ?? 0);
    return {
      key,
      label: leak.label,
      detail: leak.detail,
      hours: leak.hours,
      recoveryRate: a.recovery[key] ?? 0,
      hoursRecovered: recovered,
      valueRecovered: recovered * hourRate,
    };
  });

  const lostHoursPerProject = leakRows.reduce((s, r) => s + r.hours, 0);
  const recoveredHoursPerProject = leakRows.reduce(
    (s, r) => s + r.hoursRecovered,
    0,
  );
  const netHoursPerProject = recoveredHoursPerProject - a.processOverheadHours;

  const netHoursPerYear = netHoursPerProject * a.projectsPerYear;
  const netValuePerYear = netHoursPerYear * hourRate;

  const firstYearValue = netValuePerYear - a.setupHoursOneOff * hourRate;

  const daysReleasedPerYear = netHoursPerYear / a.hoursPerDay;
  const extraProjectCapacity =
    netHoursPerYear / (lostHoursPerProject + a.processOverheadHours || 1);

  const biggerProjectUpside =
    a.biggerProjects.extraWinsPerYear * a.biggerProjects.targetCeiling;

  /* Worth separating: recovered rework/waiting/scramble hours are COST SAVED
     (capacity released to sell again), whereas recovered "unbilled changes"
     are REVENUE NEWLY CAPTURED — work the client was always going to ask for
     and would have had for free. They are different arguments and management
     hears them differently, so the deck shows the split. */
  const unbilledRow = leakRows.find((r) => r.key === "unbilledChanges");
  const newRevenuePerProject = unbilledRow ? unbilledRow.hoursRecovered * hourRate : 0;
  const newRevenuePerYear = newRevenuePerProject * a.projectsPerYear;

  /* The fixed-price argument. Projects are sold for a price, not for a number
     of hours, so every hour NOT spent on rework is margin. The same saved
     hours can be banked one of two ways — as margin on the jobs we already
     have, or as capacity to take on more. They are the same hours counted
     differently, so the deck presents them as alternatives, never as a sum. */
  const impliedHoursPerProject = a.avgProjectValue / hourRate;
  const hoursAfter = impliedHoursPerProject - netHoursPerProject;
  const marginNowPct = 0; // baseline: price == cost of delivery at this rate
  const marginAfterPct = (netHoursPerProject / impliedHoursPerProject) * 100;
  const capacityHoursFreed = netHoursPerProject * a.projectsPerYear;
  const extraProjectsPerYear = capacityHoursFreed / impliedHoursPerProject;
  const extraRevenueIfSold = extraProjectsPerYear * a.avgProjectValue;

  return {
    hourRate,
    leakRows,
    lostHoursPerProject,
    lostValuePerProject: lostHoursPerProject * hourRate,
    lostValuePerYear: lostHoursPerProject * hourRate * a.projectsPerYear,
    recoveredHoursPerProject,
    netHoursPerProject,
    netHoursPerYear,
    netValuePerYear,
    firstYearValue,
    daysReleasedPerYear,
    extraProjectCapacity,
    biggerProjectUpside,
    newRevenuePerProject,
    newRevenuePerYear,
    costSavedPerYear: netValuePerYear - newRevenuePerYear,
    impliedHoursPerProject,
    hoursAfter,
    marginNowPct,
    marginAfterPct,
    capacityHoursFreed,
    extraProjectsPerYear,
    extraRevenueIfSold,
    marginPointsPerProject:
      ((netHoursPerProject * hourRate) / (a.avgProjectValue || 1)) * 100,
  };
}

export function money(n, cur = assumptions.currency) {
  const rounded = Math.round(n);
  return cur + rounded.toLocaleString("en-GB");
}

export function hours(n) {
  return (Math.round(n * 10) / 10).toLocaleString("en-GB") + " hrs";
}
